#!/usr/bin/env node
// Validate, redact and summarize the porting state in reports/.
//
//   npm run report              validate + write reports/summary.md (redacted)
//   npm run report -- --fix     also redact sensitive strings in place in reports/*.md|json
//   npm run report -- --strict  exit non-zero on any validation/redaction problem
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from '../build/toolchain.mjs';
import { findSensitive, redact } from './redact.mjs';
import { REPORT_FILES, validateErrors, validateProgress, validateSubsystemMap } from './schema.mjs';

const R = join(ROOT, 'reports');
const argv = process.argv.slice(2);
const fix = argv.includes('--fix');
const strict = argv.includes('--strict');

const readJson = (f) => {
  try {
    return JSON.parse(readFileSync(join(R, f), 'utf8'));
  } catch (e) {
    return existsSync(join(R, f)) ? { __error: e.message } : null;
  }
};

const problems = [];
const present = {};
for (const f of Object.keys(REPORT_FILES)) present[f] = existsSync(join(R, f));

const sub = readJson('subsystem-map.json');
if (sub?.__error) problems.push(`subsystem-map.json: ${sub.__error}`);
else if (sub) problems.push(...validateSubsystemMap(sub));
const prog = readJson('progress.json');
if (prog?.__error) problems.push(`progress.json: ${prog.__error}`);
else if (prog) problems.push(...validateProgress(prog));
const errs = readJson('errors.json');
if (errs?.__error) problems.push(`errors.json: ${errs.__error}`);
else if (errs) problems.push(...validateErrors(errs));

// redaction scan over every text report
const sensitive = [];
if (existsSync(R)) {
  for (const f of readdirSync(R)) {
    const p = join(R, f);
    if (!statSync(p).isFile() || !/\.(md|json|txt)$/.test(f)) continue;
    const text = readFileSync(p, 'utf8');
    const hits = findSensitive(text);
    if (hits.length && fix) {
      writeFileSync(p, redact(text));
      sensitive.push(...hits.map((h) => `${f}: ${h.rule} (redacted)`));
    } else {
      sensitive.push(...hits.map((h) => `${f}: ${h.rule}`));
    }
  }
}

// e2e summary (Playwright JSON reporter)
let e2e = null;
const pw = readJson('e2e-results.json');
if (pw && !pw.__error && pw.stats) {
  const tests = [];
  const visit = (suite, path) => {
    for (const s of suite.suites ?? []) visit(s, [...path, s.title]);
    for (const sp of suite.specs ?? []) for (const t of sp.tests ?? []) tests.push({ title: [...path, sp.title].filter(Boolean).join(' › '), project: t.projectName, status: t.status });
  };
  for (const s of pw.suites ?? []) visit(s, []);
  e2e = { expected: pw.stats.expected, unexpected: pw.stats.unexpected, skipped: pw.stats.skipped, flaky: pw.stats.flaky, tests };
}

const inv = readJson('inventory.json');
const lines = [
  '# Porting state summary (generated)',
  '',
  `Generated by \`npm run report\` at ${new Date().toISOString()}. This file is machine-generated; the narrative lives in final-report.md.`,
  '',
  '## Files',
  '',
  ...Object.entries(REPORT_FILES).map(([f, who]) => `- [${present[f] ? 'x' : ' '}] \`${f}\` — ${who}`),
  '',
];
if (inv && !inv.__error) {
  lines.push('## Inventory', '', `${inv.files.length} file(s), candidates: ${inv.candidates.map((c) => `${c.path} (${c.format}, ${c.confidence})`).join(', ') || 'none'}`, `REA: ${inv.tools?.rea?.available ? 'detected' : 'not detected'}`, '');
}
if (prog && !prog.__error) lines.push('## Progress', '', `Game: ${prog.game}  •  achieved **${prog.achieved_level}** (target ${prog.target_level})`, `Next: ${prog.next}`, '');
if (sub && !sub.__error) {
  lines.push('## Subsystems', '', '| subsystem | strategy | status | confidence | deviations |', '|---|---|---|---|---|');
  for (const s of sub.subsystems) lines.push(`| ${s.name} | ${s.implementation_strategy} | ${s.status} | ${s.confidence} | ${(s.known_deviations ?? []).length} |`);
  lines.push('');
}
if (e2e) {
  lines.push('## Browser E2E', '', `passed ${e2e.expected}, failed ${e2e.unexpected}, skipped ${e2e.skipped}, flaky ${e2e.flaky}`, '');
  for (const t of e2e.tests) lines.push(`- ${t.status === 'expected' ? 'PASS' : t.status === 'skipped' ? 'SKIP' : 'FAIL'} [${t.project}] ${t.title}`);
  lines.push('');
}
lines.push('## Checks', '', problems.length ? problems.map((p) => `- schema: ${p}`).join('\n') : '- schema: ok', sensitive.length ? sensitive.map((s) => `- redaction: ${s}`).join('\n') : '- redaction: ok', '');

writeFileSync(join(R, 'summary.md'), redact(lines.join('\n')));
console.log(`report: wrote reports/summary.md (${problems.length} schema problem(s), ${sensitive.length} redaction finding(s))`);
for (const p of problems) console.log(`  schema: ${p}`);
for (const s of sensitive) console.log(`  redaction: ${s}`);
if (strict && (problems.length || (sensitive.length && !fix))) process.exit(1);
