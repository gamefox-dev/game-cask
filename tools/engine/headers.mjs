// One source of truth for engine bundle MIME types and response headers: the local server applies exactly
// what the bundle's deploy config (_headers, headers.json) declares. Threaded runtimes need cross-origin
// isolation (SharedArrayBuffer): COOP same-origin + COEP require-corp on every response.
export const MIME = Object.freeze({ '.html': 'text/html; charset=utf-8', '.js': 'application/javascript', '.wasm': 'application/wasm',
  '.pck': 'application/octet-stream', '.json': 'application/json', '.txt': 'text/plain; charset=utf-8', '': 'text/plain; charset=utf-8' });
// Subresources/connects/embeds stay same-origin. CSP is not an OS sandbox.
export const CSP = "default-src 'self' data: blob:; script-src 'self' 'unsafe-inline' 'unsafe-eval' blob:; style-src 'self' 'unsafe-inline'; connect-src 'self' blob: data:; worker-src 'self' blob:; frame-src 'none'; object-src 'none'; base-uri 'none'";
export function staticHeaders({ isolation }) {
  return { schema: 'game-cask/static-headers/1', crossOriginIsolation: !!isolation,
    global: { 'X-Content-Type-Options': 'nosniff', 'Content-Security-Policy': CSP,
      ...(isolation ? { 'Cross-Origin-Opener-Policy': 'same-origin', 'Cross-Origin-Embedder-Policy': 'require-corp', 'Cross-Origin-Resource-Policy': 'same-origin' } : {}) },
    contentTypes: { '.wasm': MIME['.wasm'], '.pck': MIME['.pck'], '.js': MIME['.js'], '.html': MIME['.html'], '.json': MIME['.json'], '.txt': MIME['.txt'] } };
}
/** Netlify / Cloudflare Pages `_headers` syntax. Other static hosts: apply headers.json the same way. */
export function headersFile(h) {
  const lines = ['# Generated by Game Cask (engine bundle). Same headers as headers.json; required by the runtime.', '/*'];
  for (const [k, v] of Object.entries(h.global)) lines.push(`  ${k}: ${v}`);
  for (const [ext, type] of Object.entries(h.contentTypes)) lines.push(`/*${ext}`, `  Content-Type: ${type}`);
  return lines.join('\n') + '\n';
}
export function headersFor(h, path) {
  const ext = (path.match(/\.[a-z0-9]+$/i)?.[0] ?? '').toLowerCase();
  return { ...h.global, 'Content-Type': h.contentTypes[ext] ?? MIME[ext] ?? 'application/octet-stream' };
}
